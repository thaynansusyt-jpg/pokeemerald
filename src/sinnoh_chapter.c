void SiCoachFillCandy(void)
{
    u32 count;
    gSpecialVar_Result = FALSE;
    if (!SiIsSeason() || !FlagGet(FLAG_HE_ANTI_GRINDING)) return;
    count = CountTotalItemQuantityInBag(ITEM_RARE_CANDY);
    gSpecialVar_Result = count >= 999 || AddBagItem(ITEM_RARE_CANDY, 999 - count);
}
void SiCoachMaxIvs(void)
{
    u32 i, j;
    u8 value = 31;
    if (!SiIsSeason() || !FlagGet(FLAG_HE_ANTI_GRINDING)) return;
    for (i = 0; i < PARTY_SIZE; i++)
    {
        if (!GetMonData(&gPlayerParty[i], MON_DATA_SPECIES) || GetMonData(&gPlayerParty[i], MON_DATA_IS_EGG)) continue;
        for (j = 0; j < 6; j++) SetMonData(&gPlayerParty[i], MON_DATA_HP_IV + j, &value);
        CalculateMonStats(&gPlayerParty[i]);
    }
}

static bool8 SiHasPartner(u16 species)
{
    u32 i;
    for(i=0;i<PARTY_SIZE;i++)
        if(GetMonData(&gPlayerParty[i],MON_DATA_SPECIES)==species&&!GetMonData(&gPlayerParty[i],MON_DATA_IS_EGG))
            return TRUE;
    return FALSE;
}
void SiCheckBudew(void) {gSpecialVar_Result=SiHasPartner(SPECIES_BUDEW);}

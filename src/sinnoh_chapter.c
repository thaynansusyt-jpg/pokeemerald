void SiInferStarter(void)
{
    u32 i,species;
    if(VarGet(VAR_SI_STARTER)>=1&&VarGet(VAR_SI_STARTER)<=3)return;
    for(i=0;i<PARTY_SIZE;i++)
    {
        species=GetMonData(&gPlayerParty[i],MON_DATA_SPECIES);
        if(species==SPECIES_TURTWIG||species==SPECIES_GROTLE||species==SPECIES_TORTERRA){VarSet(VAR_SI_STARTER,1);return;}
        if(species==SPECIES_CHIMCHAR||species==SPECIES_MONFERNO||species==SPECIES_INFERNAPE){VarSet(VAR_SI_STARTER,2);return;}
        if(species==SPECIES_PIPLUP||species==SPECIES_PRINPLUP||species==SPECIES_EMPOLEON){VarSet(VAR_SI_STARTER,3);return;}
    }
    VarSet(VAR_SI_STARTER,1);
}
